<script lang="ts">
	import { page } from '$app/state';
	import Seo from '$lib/components/Seo.svelte';
	import { loadPagefindUI } from '$lib/search/pagefind';
	import { onMount } from 'svelte';

	let status = $state<'loading' | 'ready' | 'unavailable'>('loading');

	onMount(async () => {
		try {
			const PagefindUI = await loadPagefindUI();
			const ui = new PagefindUI({
				element: '#pagefind',
				showImages: false,
				showSubResults: true,
				resetStyles: false,
				translations: { placeholder: 'Search rides, parks and pairings' }
			});
			status = 'ready';

			// Makes /search?q=… a real, linkable search.
			const term = page.url.searchParams.get('q');
			if (term) ui.triggerSearch?.(term);
		} catch {
			status = 'unavailable';
		}
	});
</script>

<Seo
	title="Search"
	description="Search every ride, park and pairing."
	path="/search"
	noindex={true}
/>

<div class="page section search">
	<header class="search__header">
		<p class="eyebrow">Look something up</p>
		<h1>Search</h1>
	</header>

	<div id="pagefind" class="search__ui"></div>

	{#if status === 'loading'}
		<p class="muted">Loading the index…</p>
	{:else if status === 'unavailable'}
		<p class="search__note">
			The search index is not available. It is generated by the
			<code>postbuild</code> step, so it is missing when running the dev server — try
			<code>npm run build &amp;&amp; npm run preview</code>. In the meantime you can browse
			<a href="/rides">all rides</a>, <a href="/parks">all parks</a> or
			<a href="/pairings">all pairings</a>.
		</p>
	{/if}

	<noscript>
		<p class="search__note">
			Search needs JavaScript. Everything is browsable without it:
			<a href="/rides">all rides</a>, <a href="/parks">all parks</a> and
			<a href="/pairings">all pairings</a>, grouped by moment.
		</p>
	</noscript>
</div>

